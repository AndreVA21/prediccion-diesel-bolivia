from sklearn.preprocessing import MinMaxScaler

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 1 — CARGA DE DATOS Y SERIE HISTÓRICA                ║
║  Bolivia: Producción de Refinados de Petróleo 1990-2024     ║
╚══════════════════════════════════════════════════════════════╝

Qué hace este bloque:
  - Lee el archivo Excel del INE/Ministerio de Hidrocarburos
  - Parsea la estructura anidada (años + meses + columnas)
  - Detecta años con sufijo "(p)" = datos preliminares
  - Genera la serie histórica anual de Diésel en gráfica de barras
"""

import re
import pandas as pd
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

# ── Configuración ──────────────────────────────────────────────
ARCHIVO = "/content/4. Bolivia - Produccion Refinados de Petroleo segun Año y Mes 1990 - 2024.xlsx"
HOJA    = "H04"

MESES = {
    "enero": 1, "febrero": 2, "marzo": 3, "abril": 4,
    "mayo": 5, "junio": 6, "julio": 7, "agosto": 8,
    "septiembre": 9, "octubre": 10, "noviembre": 11, "diciembre": 12,
}

COLUMNAS = [
    "GASOLINA_AUTOMOTOR", "GASOLINA_AVIACION", "GAS_LICUADO",
    "KEROSENO", "JET_FUEL", "DIESEL", "FUEL_OIL",
    "ACEITES_AUTOMOTORES", "ACEITES_INDUSTRIALES",
    "GRASAS", "ASFALTO", "PARAFINA",
]

# ── Función de carga ────────────────────────────────────────────
def cargar_datos(path: str) -> pd.DataFrame:
    """
    Lee el Excel y devuelve un DataFrame limpio con columnas:
    ANIO, MES, FECHA, [12 productos], PRELIMINAR (bool),
    TOTAL_CARBURANTES, TOTAL_PRODUCCION.

    El Excel tiene estructura compleja:
      - Fila de año:  '1990', '2022(p)', etc.  → marca el año actual
      - Fila de mes:  'Enero', 'Febrero', etc. → fila de datos
      - Las primeras 10 filas son encabezados/títulos → se ignoran
    """
    raw = pd.read_excel(path, sheet_name=HOJA, header=None)

    anio_actual  = None
    es_preliminar = False
    registros    = []

    for _, fila in raw.iterrows():
        periodo = fila.iloc[1]
        if pd.isna(periodo):
            continue

        periodo_str = str(periodo).strip()

        # ¿Es una fila de año? (ej: '1990', '2022(p)')
        match = re.match(r"^(\d{4})", periodo_str)
        if match:
            anio_actual   = int(match.group(1))
            es_preliminar = "(p)" in periodo_str.lower()
            continue  # fila de totales anuales → no la usamos

        # ¿Es una fila de mes?
        mes_num = MESES.get(periodo_str.lower().rstrip())
        if mes_num is None or anio_actual is None:
            continue

        # Extraer los 12 valores de productos
        valores = list(fila.iloc[2:14])
        if len(valores) < len(COLUMNAS):
            valores += [np.nan] * (len(COLUMNAS) - len(valores))

        fila_datos = {
            "ANIO":        anio_actual,
            "MES":         mes_num,
            "PRELIMINAR":  es_preliminar,
        }
        for col, val in zip(COLUMNAS, valores):
            try:
                fila_datos[col] = float(val) if (val is not None and str(val) != "nan") else np.nan
            except (ValueError, TypeError):
                fila_datos[col] = np.nan

        registros.append(fila_datos)

    df = pd.DataFrame(registros)

    # Columna de fecha (primer día del mes)
    df["FECHA"] = pd.to_datetime(
        df["ANIO"].astype(str) + "-" + df["MES"].astype(str),
        format="%Y-%m"
    )
    df = df.sort_values("FECHA").reset_index(drop=True)

    # Totales derivados
    carburantes = ["GASOLINA_AUTOMOTOR", "GASOLINA_AVIACION", "GAS_LICUADO",
                   "KEROSENO", "JET_FUEL", "DIESEL", "FUEL_OIL"]
    df["TOTAL_CARBURANTES"] = df[carburantes].sum(axis=1, min_count=1)
    df["TOTAL_PRODUCCION"]  = df[COLUMNAS].sum(axis=1, min_count=1)

    return df


# ── Cargar ──────────────────────────────────────────────────────
print("Cargando datos...")
df = cargar_datos(ARCHIVO)

print(f"  Total registros : {len(df)}")
print(f"  Período         : {df['FECHA'].min().strftime('%b %Y')} → {df['FECHA'].max().strftime('%b %Y')}")
print(f"  Años            : {sorted(df['ANIO'].unique())}")
print(f"  Datos prelim.   : {df[df['PRELIMINAR']]['ANIO'].unique().tolist()}")
print()
print(df[["FECHA", "DIESEL", "GASOLINA_AUTOMOTOR", "GAS_LICUADO", "PRELIMINAR"]].tail(10).to_string())

# ── Gráfica: serie histórica anual de Diésel ───────────────────
diesel_anual = (
    df.groupby(["ANIO", "PRELIMINAR"])["DIESEL"]
    .sum()
    .reset_index()
)
confirmado   = diesel_anual[~diesel_anual["PRELIMINAR"]]
preliminar   = diesel_anual[ diesel_anual["PRELIMINAR"]]

fig, ax = plt.subplots(figsize=(14, 5))
ax.bar(confirmado["ANIO"], confirmado["DIESEL"],
       color="#378ADD", alpha=0.85, label="Confirmado")
ax.bar(preliminar["ANIO"], preliminar["DIESEL"],
       color="#EF9F27", alpha=0.85, label="Preliminar (p)")

# Línea de tendencia (regresión lineal simple)
x = diesel_anual["ANIO"].values
y = diesel_anual["DIESEL"].values
m, b = np.polyfit(x[-15:], y[-15:], 1)          # tendencia últimos 15 años
x_trend = np.linspace(x[-15], x[-1] + 3, 50)
ax.plot(x_trend, m * x_trend + b, "--", color="#E63946", lw=1.5, label="Tendencia 2010-2024")

ax.set_title("Bolivia: Producción anual de Diésel (1990–2024)", fontsize=13, pad=12)
ax.set_xlabel("Año")
ax.set_ylabel("Miles de barriles")
ax.legend(fontsize=9)
ax.annotate("Pico: 2015\n~6.323 mbbl",
            xy=(2015, 6322.7), xytext=(2010, 6600),
            arrowprops=dict(arrowstyle="->", color="gray"), fontsize=9, color="gray")
plt.tight_layout()
plt.savefig("bloque1_serie_historica.png", dpi=150, bbox_inches="tight")
plt.close()
print("\nGráfica guardada: bloque1_serie_historica.png")

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 2 — PREPARACIÓN DE LA SERIE TEMPORAL                ║
╚══════════════════════════════════════════════════════════════╝

Qué hace:
  - Selecciona la variable (Diésel)
  - Convierte a serie temporal mensual
  - Maneja valores faltantes
  - Divide en train/test (80/20)
"""

# Serie mensual de diésel
serie = df.set_index("FECHA")["DIESEL"].asfreq("MS")

# Interpolar valores faltantes
serie = serie.interpolate()

# División train/test (IMPORTANTE: respeta el tiempo)
split = int(len(serie) * 0.8)
train = serie.iloc[:split]
test  = serie.iloc[split:]

print("Train:", len(train), "Test:", len(test))
print("Periodo train:", train.index.min(), "→", train.index.max())
print("Periodo test :", test.index.min(), "→", test.index.max())

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 3 — MODELO ARIMA                                   ║
╚══════════════════════════════════════════════════════════════╝
"""

from statsmodels.tsa.arima.model import ARIMA

# Modelo base
model_arima = ARIMA(train, order=(2,1,2))
model_arima_fit = model_arima.fit()

# Predicción
pred_arima = model_arima_fit.forecast(steps=len(test))

print("ARIMA listo")

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 4 — MODELO LSTM                                    ║
╚══════════════════════════════════════════════════════════════╝
"""
# Escalar datos
scaler = MinMaxScaler()
train_scaled = scaler.fit_transform(train.values.reshape(-1,1))
test_scaled  = scaler.transform(test.values.reshape(-1,1))

def crear_dataset(data, window=12):
    X, y = [], []
    for i in range(window, len(data)):
        X.append(data[i-window:i])
        y.append(data[i])
    return np.array(X), np.array(y)

X_train, y_train = crear_dataset(train_scaled)
X_test, y_test   = crear_dataset(test_scaled)

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense

model_lstm = Sequential()
model_lstm.add(LSTM(50, activation='relu', input_shape=(X_train.shape[1], 1)))
model_lstm.add(Dense(1))

model_lstm.compile(optimizer='adam', loss='mse')

model_lstm.fit(X_train, y_train, epochs=20, verbose=1)

pred_lstm = model_lstm.predict(X_test)

# Desnormalizar
pred_lstm = scaler.inverse_transform(pred_lstm)
y_test_real = scaler.inverse_transform(y_test)

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 5 — EVALUACIÓN DE MODELOS                          ║
╚══════════════════════════════════════════════════════════════╝
"""

from sklearn.metrics import mean_absolute_error, mean_squared_error
import numpy as np

# ARIMA
mae_arima = mean_absolute_error(test, pred_arima)
rmse_arima = np.sqrt(mean_squared_error(test, pred_arima))

# LSTM
mae_lstm = mean_absolute_error(y_test_real, pred_lstm)
rmse_lstm = np.sqrt(mean_squared_error(y_test_real, pred_lstm))

print("\nRESULTADOS:")
print("ARIMA → MAE:", mae_arima, "RMSE:", rmse_arima)
print("LSTM  → MAE:", mae_lstm, "RMSE:", rmse_lstm)

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE 6 — VISUALIZACIÓN MEJORADA                           ║
╚══════════════════════════════════════════════════════════════╝
"""

import matplotlib.pyplot as plt

plt.figure(figsize=(15,6))

# ─────────────────────────────────────────────────────────────
# Serie real (train + test)
# ─────────────────────────────────────────────────────────────
plt.plot(train.index, train.values, label="Train (Real)", alpha=0.6)
plt.plot(test.index, test.values, label="Test (Real)", linewidth=2)

# ─────────────────────────────────────────────────────────────
# Predicciones
# ─────────────────────────────────────────────────────────────
plt.plot(test.index, pred_arima, label="ARIMA", linestyle="--")

# Alinear LSTM correctamente
lstm_index = test.index[-len(pred_lstm):]
plt.plot(lstm_index, pred_lstm, label="LSTM")

# ─────────────────────────────────────────────────────────────
# Línea de separación train/test
# ─────────────────────────────────────────────────────────────
plt.axvline(test.index[0], linestyle=":", linewidth=2)
plt.text(test.index[0], plt.ylim()[1]*0.95, "Inicio Test", rotation=90)

# ─────────────────────────────────────────────────────────────
# Estética
# ─────────────────────────────────────────────────────────────
plt.title("Comparación de Modelos - Producción de Diésel en Bolivia", fontsize=14)
plt.xlabel("Fecha")
plt.ylabel("Producción")
plt.legend()
plt.grid(alpha=0.3)

plt.tight_layout()
plt.show()

"""
╔══════════════════════════════════════════════════════════════╗
║  BLOQUE — ANÁLISIS AVANZADO DE ERRORES                      ║
╚══════════════════════════════════════════════════════════════╝
"""

import matplotlib.pyplot as plt
